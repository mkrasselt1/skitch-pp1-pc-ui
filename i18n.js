function detectLanguage() {
    try {
        const saved = localStorage.getItem('pp1.lang');
        if (saved && TEXTS[saved]) return saved;
    } catch {
        // Speicher nicht verfügbar: Browsersprache nehmen
    }
    for (const l of navigator.languages ?? [navigator.language]) {
        const code = (l || '').slice(0, 2).toLowerCase();
        if (TEXTS[code]) return code;
    }
    return 'en';
}

let lang = detectLanguage();

function t(key, params = {}) {
    const s = TEXTS[lang][key] ?? TEXTS.de[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

// Zahlen im Format der gewählten Sprache
const fmtNumber = (n) => Number(n).toLocaleString(LOCALES[lang]);
const currentLocale = () => LOCALES[lang];

function applyI18n(root = document) {
    document.documentElement.lang = lang;
    document.title = t('app.title');
    for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
    for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
    for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
}

function setLanguage(code) {
    if (!TEXTS[code]) return;
    lang = code;
    try {
        localStorage.setItem('pp1.lang', code);
    } catch {
        // nicht speicherbar: gilt nur bis zum Neuladen
    }
    applyI18n();
    document.dispatchEvent(new CustomEvent('pp1-language'));
}

document.addEventListener('DOMContentLoaded', () => {
    const select = document.getElementById('langSelect');
    for (const [code, name] of Object.entries(LANGUAGES)) {
        const o = document.createElement('option');
        o.value = code;
        o.textContent = name;
        select.append(o);
    }
    select.value = lang;
    select.addEventListener('change', () => setLanguage(select.value));
    applyI18n();
});
